export function dailyReading(sign: ZodiacSign, date: string) {
  const daysSinceEpoch = Date.parse(date) / 86_400_000;
  const cycle = readings[sign];
  const index = ((daysSinceEpoch % cycle.length) + cycle.length) % cycle.length;
  return cycle[index];
}
